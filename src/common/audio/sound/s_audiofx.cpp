void S_ParseAudioFXDef()
{
	int lump, lastlump = 0;

	while ((lump = fileSystem.FindLump("AUDIOFX", &lastlump)) != -1)
	{
		FScanner sc;
		sc.OpenLumpNum(lump);
		S_ReadAudioFXDef(sc);
	}
}